export function createAgentSnapshot(song, selection, playback = {
  status: "stopped",
  currentTick: 0,
  currentNoteId: null,
  currentSectionId: song.sections[0]?.id ?? null,
  tempo: song.timing.tempo,
  loop: { enabled: false, startTick: 0, endTick: 1 }
}, editor = { snap: "1/8", tool: "select", canPaste: false, clipboardCount: 0 }, selectedNoteIds = [], view = { mode: "combined", follow: true }, generation = {
  status: "idle",
  stale: false,
  gap: null,
  seed: null,
  candidateIds: [],
  activeCandidateId: null,
  auditionCandidateId: null,
  candidates: [],
  acceptedNoteIds: []
}, history = { canUndo: false, canRedo: false, undoDepth: 0, redoDepth: 0 }, selectedPercussionHitIds = [], mix = { channels: {} }, harmony = { status: "idle", range: null, candidates: [], selectedCandidateId: null }, harmonyContext = { selectedChordId: null, harmonyRange: null }) {
  const currentSyllableId = getActiveSyllableId(song.lyrics, playback.currentNoteId);
  const currentSyllableIds = currentSyllableId ? [currentSyllableId] : [];
  return {
    song: {
      id: song.id,
      title: song.title,
      tempo: song.timing.tempo,
      key: song.key,
      scale: cloneData(song.scale),
      timeSignature: cloneData(song.timing.timeSignature),
      currentSectionId: playback.currentSectionId,
      notes: cloneData(song.notes),
      lyrics: cloneData(song.lyrics),
      sections: cloneData(song.sections),
      phrases: cloneData(song.phrases),
      chords: cloneData(song.chords),
      tracks: cloneData(song.tracks),
      sketch: cloneData(song.sketch),
      ...(song.mix ? { mix: cloneData(song.mix) } : {})
    },
    playback: {
      status: playback.status,
      currentTick: playback.currentTick,
      currentNoteId: playback.currentNoteId,
      currentSyllableId,
      currentSyllableIds,
      currentSectionId: playback.currentSectionId,
      tempo: playback.tempo,
      loop: cloneData(playback.loop)
    },
    selection: cloneData(selection),
    selectedNoteIds: cloneData(selectedNoteIds),
    selectedPercussionHitIds: cloneData(selectedPercussionHitIds),
    mix: cloneData(mix),
    editor: cloneData(editor),
    view: cloneData(view),
    generation: cloneData(generation),
    harmony: cloneData(harmony),
    selectedChordId: harmonyContext.selectedChordId,
    harmonyRange: cloneData(harmonyContext.harmonyRange),
    anchorNoteIds: song.notes.filter((note) => note.anchor).map((note) => note.id),
    lockedNoteIds: song.notes.filter((note) => note.locked).map((note) => note.id),
    history: cloneData(history),
    availableActions: [...AVAILABLE_ACTIONS]
  };
}
